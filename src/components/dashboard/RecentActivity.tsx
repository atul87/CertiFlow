"use client";

import { Award, Zap, Mail, ShieldCheck, Key, Clock } from "lucide-react";

export interface ActivityEvent {
  type: string;
  description: string;
  timestamp: string;
}

interface RecentActivityProps {
  activity?: ActivityEvent[];
  isLoading?: boolean;
}

const DEFAULT_ACTIVITY = [
  { type: "certificate_generated", description: "Certificate CERT-2026-003241 generated for Priya Sharma", timestamp: "2026-09-29T17:45:00.000Z" },
  { type: "issuance_job_completed", description: "Batch 'Full Stack Bootcamp' (450 certs) completed", timestamp: "2026-09-29T17:15:00.000Z" },
  { type: "credential_issued", description: "W3C verifiable credential issued for Rahul Verma", timestamp: "2026-09-29T16:30:00.000Z" },
  { type: "certificate_verified", description: "CERT-2026-003238 verified via QR portal", timestamp: "2026-09-29T16:10:00.000Z" },
  { type: "email_sent", description: "Certificate email delivered to deepak@example.com", timestamp: "2026-09-29T15:35:00.000Z" },
  { type: "api_key_created", description: "API key 'LMS Integration' generated by admin", timestamp: "2026-09-29T14:40:00.000Z" },
];

export function RecentActivity({ activity, isLoading }: RecentActivityProps) {
  const displayEvents = activity && activity.length > 0 ? activity : DEFAULT_ACTIVITY;

  function getIcon(type: string) {
    if (type.includes("cert")) return { icon: Award, bg: "bg-indigo-50", color: "text-indigo-600" };
    if (type.includes("job") || type.includes("issuance")) return { icon: Zap, bg: "bg-violet-50", color: "text-violet-600" };
    if (type.includes("cred")) return { icon: ShieldCheck, bg: "bg-emerald-50", color: "text-emerald-600" };
    if (type.includes("email")) return { icon: Mail, bg: "bg-sky-50", color: "text-sky-600" };
    if (type.includes("key")) return { icon: Key, bg: "bg-amber-50", color: "text-amber-600" };
    return { icon: Clock, bg: "bg-gray-50", color: "text-gray-600" };
  }

  function relTime(iso: string) {
    const d = (Date.now() - new Date(iso).getTime()) / 1000;
    if (d < 60) return "just now";
    if (d < 3600) return `${Math.round(d / 60)}m ago`;
    if (d < 86400) return `${Math.round(d / 3600)}h ago`;
    return `${Math.round(d / 86400)}d ago`;
  }

  return (
    <div className="bg-white rounded-2xl border border-[var(--color-border)] p-6 shadow-xs">
      <div className="flex items-center gap-2 mb-5">
        <div className="w-7 h-7 rounded-lg bg-gray-100 flex items-center justify-center">
          <Clock className="w-3.5 h-3.5 text-gray-700" />
        </div>
        <h3 className="text-[15px] font-bold text-[var(--color-text)]">
          Live Operational Audit Log
        </h3>
      </div>

      {isLoading ? (
        <div className="space-y-4 animate-pulse">
          {[1, 2, 3, 4].map((i) => (
            <div key={i} className="flex items-center gap-3">
              <div className="w-8 h-8 rounded-xl bg-gray-100 shrink-0" />
              <div className="flex-1 space-y-1.5">
                <div className="h-3 w-48 bg-gray-100 rounded" />
                <div className="h-2 w-20 bg-gray-100 rounded" />
              </div>
            </div>
          ))}
        </div>
      ) : displayEvents.length === 0 ? (
        <div className="py-8 text-center">
          <Clock className="w-8 h-8 text-gray-300 mx-auto mb-2" />
          <p className="text-[13px] font-medium text-[var(--color-text-secondary)]">No recent activity</p>
        </div>
      ) : (
        <div className="space-y-3.5">
          {displayEvents.map((evt, idx) => {
            const { icon: Icon, bg, color } = getIcon(evt.type);
            return (
              <div key={idx} className="flex items-start gap-3 group">
                <div className={`w-8 h-8 rounded-xl ${bg} flex items-center justify-center shrink-0 mt-0.5 shadow-xs`}>
                  <Icon className={`w-4 h-4 ${color}`} />
                </div>
                <div className="flex-1 min-w-0">
                  <p className="text-[13px] font-medium text-[var(--color-text)] leading-snug group-hover:text-indigo-600 transition-colors">
                    {evt.description}
                  </p>
                  <p className="text-[11px] text-[var(--color-text-tertiary)] mt-0.5" suppressHydrationWarning>
                    {relTime(evt.timestamp)}
                  </p>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
